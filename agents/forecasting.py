"""Agent 4: Demand forecasting.

Tracks how often each skill is asked for across the postings the system has
seen, then projects that forward. The candidate gets an answer to a question a
job board cannot give them: not what is being asked for today, but what is
being asked for more often than it was a month ago.

A deliberate contrast with the healthcare forecasting work that preceded this
project. There, quarterly occupancy returns were forecast at monthly frequency
with yearly seasonality enabled, which left eight unconstrained months a year
and produced predictions that had to be clipped before they reached the screen.
Here the observation frequency and the forecast frequency are the same, weekly,
because the counts are generated by the ingestion agent's own weekly run. The
mismatch that caused that failure cannot arise.

Prophet needs a reasonable history before it says anything useful. Below that
threshold the agent reports insufficient history rather than fitting a model to
three points and presenting the result as a forecast.
"""

from __future__ import annotations

import logging
from collections import defaultdict
from dataclasses import dataclass, field
from datetime import UTC, date, datetime, timedelta
from enum import Enum

from agents.extraction import Confidence, Requirements

logger = logging.getLogger(__name__)

# Prophet is imported lazily. It is a heavy dependency with a compiled backend,
# and the counting and trend logic below is worth testing without it.
_PROPHET_IMPORT_ERROR: str | None = None

# Minimum weekly observations before a forecast is attempted. Below this the
# agent says so rather than extrapolating from noise.
MIN_WEEKS_FOR_FORECAST = 8

# Weeks averaged to form the current baseline a forecast is compared against.
BASELINE_WEEKS = 3

# Reconstructed history must rest on at least this many real postings before a
# share trend is reported. Roughly three postings a week across eight weeks.
MIN_BOOTSTRAP_POSTINGS = 24

# Percentage point move that counts as a genuine shift in a share series.
SHARE_TREND_POINTS = 3.0

# If at least this fraction of trending skills move the same way, the report
# is flagged as likely reflecting the data rather than the market.
UNIFORM_MOVEMENT_THRESHOLD = 0.85
UNIFORM_MOVEMENT_MIN_SKILLS = 5

# A skill must be projected to reach at least this rate before emerging from a
# zero baseline counts as rising rather than noise.
MIN_EMERGING_RATE = 2.0

# A skill must appear this many times in total to be worth modelling at all.
MIN_TOTAL_MENTIONS = 5

# Percentage change over the forecast horizon that counts as a real move
# rather than week to week noise.
TREND_THRESHOLD_PCT = 10.0


class Trend(str, Enum):
    RISING = "rising"
    STABLE = "stable"
    FALLING = "falling"
    INSUFFICIENT_HISTORY = "insufficient_history"


@dataclass
class SkillDemand:
    skill: str
    total_mentions: int
    weeks_observed: int
    current_weekly_rate: float
    trend: Trend
    # Populated only when a model was actually fitted.
    forecast_weekly_rate: float | None = None
    change_pct: float | None = None
    # Absolute move. For shares this is percentage points, the honest measure:
    # three percent to seven point six percent is plus four point six points,
    # which "+155%" dramatically overstates.
    change_points: float | None = None
    note: str = ""
    # Which engine produced the projection, so a degraded run is visible in
    # the output rather than silently passing as a Prophet forecast.
    method: str = "prophet"

    @property
    def is_forecast(self) -> bool:
        return self.forecast_weekly_rate is not None


@dataclass
class DemandReport:
    generated_for_week: date
    skills: list[SkillDemand] = field(default_factory=list)
    # Snapshot history counts postings per week. Reconstructed history records
    # the percentage of postings mentioning a skill. The two must be labelled
    # differently or a share of 12 percent reads as twelve postings a week.
    rate_unit: str = "per week"

    def rising(self, limit: int = 10) -> list[SkillDemand]:
        movers = [s for s in self.skills if s.trend is Trend.RISING]
        return sorted(movers, key=lambda s: s.change_pct or 0, reverse=True)[:limit]

    def falling(self, limit: int = 10) -> list[SkillDemand]:
        movers = [s for s in self.skills if s.trend is Trend.FALLING]
        return sorted(movers, key=lambda s: s.change_pct or 0)[:limit]

    def most_demanded(self, limit: int = 15) -> list[SkillDemand]:
        return sorted(self.skills, key=lambda s: s.total_mentions, reverse=True)[:limit]

    @property
    def uniform_movement(self) -> Trend | None:
        """Return a direction if nearly every forecast skill shares it.

        Genuine markets do not move every skill the same way at once. When they
        appear to, the cause is almost always in the data rather than the
        market: a shift in how complete the postings were, a change in which
        sources responded, or a stale week pulling the fit. Two consecutive
        live runs showed every major skill falling and then every one rising,
        and this check would have flagged both.
        """
        called = [s for s in self.skills if s.trend in (Trend.RISING, Trend.FALLING)]
        if len(called) < UNIFORM_MOVEMENT_MIN_SKILLS:
            return None
        rising = sum(1 for s in called if s.trend is Trend.RISING)
        share_rising = rising / len(called)
        if share_rising >= UNIFORM_MOVEMENT_THRESHOLD:
            return Trend.RISING
        if share_rising <= 1 - UNIFORM_MOVEMENT_THRESHOLD:
            return Trend.FALLING
        return None


