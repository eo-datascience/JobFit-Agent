def _load_prophet():
    global _PROPHET_IMPORT_ERROR
    try:
        from prophet import Prophet
    except ImportError as exc:  # pragma: no cover - environment dependent
        _PROPHET_IMPORT_ERROR = str(exc)
        return None
    return Prophet


def classify_share_trend(current: float, predicted: float) -> tuple[Trend, float]:
    """Classify a share series by its move in percentage points.

    A relative threshold is wrong for shares. On a small base a single extra
    posting clears any percentage threshold, which is how one posting a week
    became "+155%". Requiring a move of a few points means the change has to
    reflect more than one listing.
    """
    points = predicted - current
    if points >= SHARE_TREND_POINTS:
        return Trend.RISING, points
    if points <= -SHARE_TREND_POINTS:
        return Trend.FALLING, points
    return Trend.STABLE, points


def classify_trend(current: float, predicted: float) -> tuple[Trend, float]:
    """Compare a predicted rate against the current one.

    The threshold exists because a weekly count moving from 4 to 5 is noise,
    not a signal, and labelling it as growth would make every skill look like
    it is moving.
    """
    if current <= 0:
        # Growth from zero has no meaningful percentage. Reporting "+100%" here
        # was how a skill with no recent mentions appeared at the top of the
        # rising list. A skill emerging from nothing is noted without a figure.
        return (Trend.RISING, 0.0) if predicted >= MIN_EMERGING_RATE else (Trend.STABLE, 0.0)

    change = ((predicted - current) / current) * 100
    if change >= TREND_THRESHOLD_PCT:
        return Trend.RISING, change
    if change <= -TREND_THRESHOLD_PCT:
        return Trend.FALLING, change
    return Trend.STABLE, change


def _apply_trend(base: SkillDemand, current: float, predicted: float, share_mode: bool) -> None:
    """Record the projection and classify it with the right measure."""
    points = predicted - current
    if share_mode:
        trend, _ = classify_share_trend(current, predicted)
    else:
        trend, _ = classify_trend(current, predicted)
    _, relative = classify_trend(current, predicted)
    base.forecast_weekly_rate = round(predicted, 2)
    base.change_pct = round(relative, 1)
    base.change_points = round(points, 1)
    base.trend = trend


def _least_squares_projection(filled: dict[date, int], horizon_weeks: int) -> float:
    """Project the series forward with an ordinary least squares line.

    Used when Prophet is not installed. On a couple of months of weekly points
    there is no seasonality to discover, so a straight line is close to what
    Prophet would produce anyway. Prophet earns its place on longer series and
    for its uncertainty intervals, not on eight points.
    """
    weeks = sorted(filled)
    ordered = [float(filled[week]) for week in weeks]
    n = len(ordered)
    # Elapsed weeks from the first observation, not list position. With
    # reconstructed history the observations are not evenly spaced, and using
    # positions made a January week sit beside a July one as if they were
    # consecutive, turning the gap between them into a steep weekly slide.
    first = weeks[0]
    xs = [(week - first).days / 7 for week in weeks]
    mean_x = sum(xs) / n
    mean_y = sum(ordered) / n
    denominator = sum((x - mean_x) ** 2 for x in xs)
    if denominator == 0:
        return mean_y
    slope = sum((x - mean_x) * (y - mean_y) for x, y in zip(xs, ordered, strict=True)) / denominator
    intercept = mean_y - slope * mean_x
    return max(0.0, intercept + slope * (xs[-1] + horizon_weeks))


def forecast_skill(
    skill: str,
    series: dict[date, int],
    horizon_weeks: int = 4,
    prophet_cls=None,
    zero_fill: bool = True,
    raw_total: int | None = None,
    share_mode: bool = False,
) -> SkillDemand:
    """Forecast one skill's weekly demand.

    Returns an honest result when there is not enough history, rather than
    fitting a model to a handful of points and presenting it as a prediction.
    """
    # Zero filling is right for recorded snapshots, where a skill absent from a
    # real weekly run genuinely had no demand. It is wrong for reconstructed
    # history, where a missing week means too few postings to measure, and
    # filling it with zero would turn "unknown" into "no demand at all".
    filled = fill_missing_weeks(series) if zero_fill else dict(sorted(series.items()))
    total = sum(filled.values())
    weeks = len(filled)

    # A trailing mean rather than the single latest week. One quiet week should
    # not decide whether a skill is rising, and the latest point is the one most
    # likely to be incomplete.
    recent = [filled[w] for w in sorted(filled)][-BASELINE_WEEKS:]
    current = sum(recent) / len(recent) if recent else 0.0

    base = SkillDemand(
        skill=skill,
        total_mentions=total,
        weeks_observed=weeks,
        current_weekly_rate=float(current),
        trend=Trend.INSUFFICIENT_HISTORY,
    )

    # In share mode the series holds percentages, so summing it says nothing
    # about how many postings sit behind a skill. A skill at three percent for
    # eight weeks sums to twenty four and would sail through a five mention
    # guard while resting on roughly one posting a week. The guard must count
    # postings, and share mode sets a higher bar because a share built on one
    # or two postings a week swings by tens of percent on a single listing.
    postings_behind = raw_total if raw_total is not None else total
    minimum = MIN_BOOTSTRAP_POSTINGS if share_mode else MIN_TOTAL_MENTIONS
    base.total_mentions = postings_behind
    if postings_behind < minimum:
        base.note = f"only {postings_behind} postings mention it, too few to call a trend"
        return base

    if weeks < MIN_WEEKS_FOR_FORECAST:
        base.note = (
            f"{weeks} weeks of history, {MIN_WEEKS_FOR_FORECAST} needed before forecasting"
        )
        return base

    Prophet = prophet_cls or _load_prophet()
    if Prophet is None:
        # Degrade to a linear trend rather than producing nothing. Prophet is a
        # heavy dependency with a compiled backend and it does not install
        # cleanly everywhere, which must not mean the agent stops working.
        predicted = _least_squares_projection(filled, horizon_weeks)
        _apply_trend(base, current, predicted, share_mode)
        base.method = "linear"
        base.note = f"{weeks} weeks of history, linear trend (prophet not installed)"
        return base

    import pandas as pd

    frame = pd.DataFrame(
        {"ds": list(filled.keys()), "y": [float(v) for v in filled.values()]}
    ).sort_values("ds")

    try:
        # Weekly observations forecast weekly. Yearly seasonality is switched
        # off deliberately: a few months of history cannot support an annual
        # cycle, and asking for one is exactly the mistake that produced
        # unusable occupancy forecasts on the previous project.
        # Prophet defaults to twenty five changepoints, which on eight weekly
        # points is meaningless and triggers a warning per skill. Scaling them
        # to the series keeps the model proportionate to the data it has.
        model = Prophet(
            weekly_seasonality=False,
            yearly_seasonality=False,
            daily_seasonality=False,
            interval_width=0.8,
            n_changepoints=max(1, min(5, len(filled) // 3)),
        )
        model.fit(frame)
        future = model.make_future_dataframe(periods=horizon_weeks, freq="W-MON")
        prediction = model.predict(future)
    except Exception as exc:  # noqa: BLE001
        # Any modelling failure degrades to no forecast rather than no report.
        logger.warning("Forecast failed for %s: %s", skill, exc)
        base.note = f"model fitting failed: {exc}"
        return base

    predicted = float(max(0.0, prediction.iloc[-1]["yhat"]))
    _apply_trend(base, current, predicted, share_mode)
    base.method = "prophet"
    base.note = f"{weeks} weeks of history"
    return base


