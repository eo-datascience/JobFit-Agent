def today() -> date:
    """Timezone aware current date.

    UK postings and a UK candidate, but pinning to UTC keeps the weekly
    buckets stable regardless of where the job happens to run.
    """
    return datetime.now(UTC).date()


def week_starting(day: date) -> date:
    """Normalise a date to the Monday of its week."""
    return day - timedelta(days=day.weekday())


def count_weekly_mentions(
    snapshots: list[tuple[date, list[Requirements]]],
) -> dict[str, dict[date, int]]:
    """Build per skill weekly counts from dated extraction snapshots.

    Each snapshot is one ingestion run. Counting the number of postings that
    mention a skill, rather than the number of mentions, prevents a single
    verbose posting that repeats "Python" twelve times from distorting the week.
    """
    counts: dict[str, dict[date, int]] = defaultdict(lambda: defaultdict(int))

    for run_date, requirements in snapshots:
        week = week_starting(run_date)
        for requirement in requirements:
            # A set, so one posting contributes at most one to each skill.
            for skill in set(requirement.skill_names):
                counts[skill][week] += 1

    return {skill: dict(weeks) for skill, weeks in counts.items()}


def fill_missing_weeks(series: dict[date, int]) -> dict[date, int]:
    """Insert explicit zeros for weeks with no mentions.

    A skill that disappears for three weeks has genuinely fallen in demand.
    Leaving those weeks absent would let Prophet interpolate straight through
    the gap and miss the decline entirely.
    """
    if not series:
        return {}

    start, end = min(series), max(series)
    filled: dict[date, int] = {}
    cursor = start
    while cursor <= end:
        filled[cursor] = series.get(cursor, 0)
        cursor += timedelta(weeks=1)
    return filled


