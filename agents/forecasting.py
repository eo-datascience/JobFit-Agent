def build_report_from_series(
    series: dict[str, dict[date, int]],
    horizon_weeks: int = 4,
    prophet_cls=None,
    zero_fill: bool = True,
    rate_unit: str = "per week",
    raw_totals: dict[str, int] | None = None,
) -> DemandReport:
    """Build a report from per skill date series.

    This is the path the pipeline uses, because history is stored as counts
    rather than as full extraction results.
    """
    latest = max(
        (d for weeks in series.values() for d in weeks),
        default=today(),
    )
    share_mode = rate_unit.startswith("%")
    results = [
        forecast_skill(
            skill, weeks, horizon_weeks, prophet_cls,
            zero_fill=zero_fill,
            raw_total=(raw_totals or {}).get(skill),
            share_mode=share_mode,
        )
        for skill, weeks in series.items()
    ]

    modelled = sum(1 for r in results if r.is_forecast)
    logger.info(
        "Demand report across %d skills. %d forecast, %d lack sufficient history.",
        len(results), modelled, len(results) - modelled,
    )
    return DemandReport(
        generated_for_week=week_starting(latest), skills=results, rate_unit=rate_unit
    )


def build_report(
    snapshots: list[tuple[date, list[Requirements]]],
    horizon_weeks: int = 4,
    prophet_cls=None,
) -> DemandReport:
    """Produce a demand report across every skill seen.

    Out of domain postings are expected to have been filtered out already by
    the extraction agent, but they are harmless here either way, since a
    marketing role contributes no taxonomy skills to count.
    """
    counts = count_weekly_mentions(snapshots)
    latest = max((d for d, _ in snapshots), default=today())

    results = [
        forecast_skill(skill, series, horizon_weeks, prophet_cls)
        for skill, series in counts.items()
    ]

    modelled = sum(1 for r in results if r.is_forecast)
    logger.info(
        "Demand report across %d skills. %d forecast, %d lack sufficient history.",
        len(results), modelled, len(results) - modelled,
    )

    return DemandReport(generated_for_week=week_starting(latest), skills=results)


# ---------------------------------------------------------------------------
# Bootstrapping history from posting dates
# ---------------------------------------------------------------------------

# A reconstructed week needs at least this many postings before its share is
# trustworthy. Two postings in a week makes every skill either 0% or 50%.
MIN_POSTINGS_PER_WEEK = 8

# Reconstruction only looks this far back. Postings still listed months after
# publication are not a random sample of their week: they are disproportionately
# the roles nobody could fill, which skew specialist and senior. Share corrects
# for how many postings survive, but not for which ones, so old weeks carry a
# different skill mix and would drag every trend line toward them.
MAX_BOOTSTRAP_WEEKS = 12


def bootstrap_series_from_posting_dates(
    requirements: list[Requirements],
    posting_dates: dict[str, date | None],
    raw_totals: dict[str, int] | None = None,
) -> dict[str, dict[date, int]]:
    """Reconstruct weekly history from the dates postings were published.

    A new deployment has no accumulated snapshots, so nothing can be forecast
    until it has run weekly for a month or more. Posting dates are already
    collected during ingestion, and job boards carry roughly the last one to
    two months, so a single run yields several weeks of history immediately.

    This carries an artefact that has to be corrected for. Older postings get
    filled and delisted, so the number of surviving postings from a given week
    falls the further back you look. Counting mentions per week would therefore
    show every skill rising toward the present, in every run, regardless of
    what the market is doing.

    The correction is to record the share of that week's postings mentioning
    each skill, scaled to a per hundred rate, rather than the raw count. Share
    is unaffected by how many postings from a week are still listed. The value
    returned is an integer rate per hundred postings, so it slots into the same
    series shape the snapshot path produces.

    The reconstruction is still weaker than accumulated snapshots, because a
    delisted posting may not be a random sample of its week. It is a starting
    point that is replaced by real history as snapshots accumulate.
    """
    postings_per_week: dict[date, int] = defaultdict(int)
    mentions_per_week: dict[str, dict[date, int]] = defaultdict(lambda: defaultdict(int))

    # Only fully described postings go into the share. An Adzuna excerpt yields
    # one or two skills where a full Reed description yields eight or ten, so
    # if the mix of the two shifts from week to week, every skill's share rises
    # or falls together for reasons that have nothing to do with the market.
    # One live run showed every major skill falling and the next showed them
    # all rising, which is the signature of a moving denominator rather than a
    # moving market.
    full_only = [r for r in requirements if r.confidence is Confidence.FULL]
    excluded = len(requirements) - len(full_only)
    if excluded:
        logger.info(
            "Excluded %d excerpt only postings from the share calculation, since "
            "they cannot show every skill a role asks for.",
            excluded,
        )

    for requirement in full_only:
        posted = posting_dates.get(requirement.posting_id)
        if posted is None:
            continue
        week = week_starting(posted)
        postings_per_week[week] += 1
        for skill in set(requirement.skill_names):
            mentions_per_week[skill][week] += 1

    # The current week is still in progress, so most skills have not appeared
    # in it yet. Treating it as a finished week made almost every skill look
    # as though it had collapsed to zero in the latest period.
    in_progress = week_starting(today())
    oldest_allowed = in_progress - timedelta(weeks=MAX_BOOTSTRAP_WEEKS)

    stale = {week for week in postings_per_week if week < oldest_allowed}
    if stale:
        logger.info(
            "Ignored %d week(s) older than %d weeks. Postings that survive that long "
            "are a biased sample of their week.",
            len(stale), MAX_BOOTSTRAP_WEEKS,
        )

    usable_weeks = {
        week for week, total in postings_per_week.items()
        if total >= MIN_POSTINGS_PER_WEEK
        and week != in_progress
        and week >= oldest_allowed
    }
    thin = len(postings_per_week) - len(usable_weeks)
    if thin:
        logger.info(
            "Dropped %d week(s) with fewer than %d postings, too thin for a reliable share.",
            thin, MIN_POSTINGS_PER_WEEK,
        )

    series: dict[str, dict[date, int]] = {}
    for skill, weeks in mentions_per_week.items():
        rates: dict[date, int] = {}
        for week in usable_weeks:
            total = postings_per_week[week]
            rates[week] = round(weeks.get(week, 0) / total * 100)
        if rates:
            series[skill] = rates
            if raw_totals is not None:
                # The real number of postings behind this skill, as opposed to
                # the sum of its percentage shares.
                raw_totals[skill] = sum(weeks.get(week, 0) for week in usable_weeks)

    if series:
        span = sorted(usable_weeks)
        logger.info(
            "Bootstrapped %d skills across %d weeks (%s to %s) from posting dates. "
            "Values are share per hundred postings, not raw counts.",
            len(series), len(span), span[0], span[-1],
        )
    return series


def build_bootstrap_report(
    requirements: list[Requirements],
    posting_dates: dict[str, date | None],
    horizon_weeks: int = 4,
    prophet_cls=None,
) -> DemandReport:
    """Demand report built from reconstructed history rather than snapshots."""
    raw_totals: dict[str, int] = {}
    series = bootstrap_series_from_posting_dates(requirements, posting_dates, raw_totals)
    return build_report_from_series(
        series, horizon_weeks, prophet_cls,
        zero_fill=False, rate_unit="% of postings", raw_totals=raw_totals,
    )
